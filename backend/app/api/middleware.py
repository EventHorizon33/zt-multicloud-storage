"""Pure-ASGI middleware: request id, client IP, body-size limits, security
headers, access log, request counters.

Security properties:
  * Every response carries ``X-Request-ID`` and security headers (CSP
    ``default-src 'none'``, ``nosniff``, frame denial, no referrer) and API
    responses carry ``Cache-Control: no-store``.
  * Request bodies are capped (``Content-Length`` checked up front, streamed
    bodies counted) so a client cannot make the server buffer unbounded
    JSON. Uploads have their own, larger cap.
  * The client IP honours ``X-Forwarded-For`` ONLY when
    ``trust_forwarded_for`` is set (ADR-0011, finding H2): ALL header lines
    are joined in order (RFC 9110 5.3), split on commas, and the entry
    ``trusted_proxy_hops`` positions from the right is the client. Every
    entry must parse as an IP (``a.b.c.d:port`` and ``[v6]:port`` have the
    port stripped); a malformed or too-short chain is rejected with 400
    ``bad-forwarded-for`` instead of falling back to another address. With
    ``trusted_proxy_cidrs`` set, the header is honoured only when the TCP
    peer is one of those proxies. The resolved IP feeds the PDP allow list,
    rate-limit keys and the audit source network.
  * The request id is ALWAYS generated by the server (finding L8). A
    client-supplied ``X-Request-ID`` (``[A-Za-z0-9._-]{1,64}``) is kept apart
    as ``client_request_id``: echoed in ``X-Client-Request-ID`` and recorded
    in audit ``details.client_request_id``, never as the audit request id.
  * The access log contains method, route path (no query string), status,
    duration and request id; never headers, bodies or tokens.
  * Every request runs inside an audit context (``app.audit.context``) so
    audit events recorded anywhere below carry its request id, client IP
    and (once authenticated) actor (finding F5).
"""
from __future__ import annotations

import ipaddress
import json
import logging
import re
import threading
import time
import uuid
from collections import Counter
from typing import Any

from app.audit.context import begin_request, end_request

log = logging.getLogger("zt.access")

_CLIENT_RID_RE = re.compile(r"^[A-Za-z0-9._-]{1,64}$")
JSON_BODY_LIMIT = 64 * 1024
MAX_FORWARDED_ENTRIES = 64
MAX_FORWARDED_BYTES = 4096
UPLOAD_PATH = "/api/files"


class BodyTooLarge(Exception):
    pass


class RequestCounters:
    """Process-wide HTTP counters for /metrics."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self.by_status: Counter[str] = Counter()

    def inc(self, status: int) -> None:
        with self._lock:
            self.by_status[str(status)] += 1

    def snapshot(self) -> dict[str, int]:
        with self._lock:
            return dict(self.by_status)


def _valid_ip(text: str | None) -> str | None:
    if not text:
        return None
    t = text.strip()
    if t.startswith("[") and "]" in t:
        t = t[1:t.index("]")]
    try:
        return str(ipaddress.ip_address(t))
    except ValueError:
        return None


class ForwardedForError(ValueError):
    """X-Forwarded-For present but unusable: the request is refused (400)."""


def _parse_forwarded_entry(text: str) -> str:
    """One X-Forwarded-For element -> normalised IP string. Accepts a bare
    IPv4/IPv6 address, ``a.b.c.d:port`` and ``[v6]`` / ``[v6]:port``.
    Anything else (names, ``unknown``, zone ids, bad ports) raises."""
    t = text.strip()
    if not t or "%" in t:
        raise ForwardedForError("empty or zoned entry")
    port = None
    if t.startswith("["):
        end = t.find("]")
        if end < 0:
            raise ForwardedForError("unterminated bracket")
        host, rest = t[1:end], t[end + 1:]
        if rest:
            if not rest.startswith(":"):
                raise ForwardedForError("garbage after bracket")
            port = rest[1:]
        try:
            ip = ipaddress.IPv6Address(host)
        except ValueError:
            raise ForwardedForError("bad bracketed address") from None
    else:
        try:
            ip = ipaddress.ip_address(t)
        except ValueError:
            if t.count(":") != 1:
                raise ForwardedForError("not an address") from None
            host, port = t.split(":")
            try:
                ip = ipaddress.IPv4Address(host)
            except ValueError:
                raise ForwardedForError("not an address") from None
    if port is not None and not (port.isdigit() and len(port) <= 5 and 0 < int(port) <= 65535):
        raise ForwardedForError("bad port")
    return str(ip)


def _peer_in(peer: str | None, cidrs: list[str]) -> bool:
    if not peer:
        return False
    try:
        ip = ipaddress.ip_address(peer)
    except ValueError:
        return False
    if isinstance(ip, ipaddress.IPv6Address) and ip.ipv4_mapped is not None:
        ip = ip.ipv4_mapped
    for c in cidrs:
        try:
            net = ipaddress.ip_network(str(c).strip(), strict=False)
        except ValueError:
            continue
        if net.version == ip.version and ip in net:
            return True
    return False


def client_ip(scope: dict, trust_forwarded_for: bool, *, hops: int = 1,
              trusted_proxy_cidrs: list[str] | tuple[str, ...] = ()) -> str | None:
    """Resolve the client IP of a request (ADR-0011). Raises
    ``ForwardedForError`` when X-Forwarded-For must be honoured but is
    malformed or shorter than ``hops`` entries."""
    client = scope.get("client")
    peer = (_valid_ip(client[0]) or client[0]) if client else None
    if not trust_forwarded_for:
        return peer
    if trusted_proxy_cidrs and not _peer_in(peer, list(trusted_proxy_cidrs)):
        return peer                      # not from one of our proxies: the header is the client's own claim
    lines = [value for name, value in scope.get("headers", []) if name == b"x-forwarded-for"]
    if not lines:
        return peer                      # did not pass through an appending proxy
    joined = b",".join(lines)
    if len(joined) > MAX_FORWARDED_BYTES:
        raise ForwardedForError("header too long")
    entries = joined.decode("latin-1").split(",")
    if len(entries) > MAX_FORWARDED_ENTRIES:
        raise ForwardedForError("too many entries")
    parsed = [_parse_forwarded_entry(e) for e in entries]
    hops = max(1, int(hops))
    if len(parsed) < hops:
        raise ForwardedForError("chain shorter than trusted_proxy_hops")
    return parsed[-hops]


def _security_headers(path: str, docs_enabled: bool, production: bool) -> list[tuple[bytes, bytes]]:
    docs = docs_enabled and (path.startswith("/docs") or path.startswith("/redoc") or path == "/openapi.json")
    csp = ("default-src 'none'; frame-ancestors 'none'; base-uri 'none'; form-action 'none'" if not docs else
           "default-src 'self'; script-src 'self' 'unsafe-inline' https://cdn.jsdelivr.net; "
           "style-src 'self' 'unsafe-inline' https://cdn.jsdelivr.net; img-src 'self' data: "
           "https://fastapi.tiangolo.com; frame-ancestors 'none'")
    headers = [
        (b"content-security-policy", csp.encode()),
        (b"x-content-type-options", b"nosniff"),
        (b"x-frame-options", b"DENY"),
        (b"referrer-policy", b"no-referrer"),
        (b"cross-origin-opener-policy", b"same-origin"),
        (b"cross-origin-resource-policy", b"same-origin"),
        (b"permissions-policy", b"camera=(), microphone=(), geolocation=(), payment=()"),
    ]
    if path.startswith("/api/") or path == "/metrics":
        headers += [(b"cache-control", b"no-store"), (b"pragma", b"no-cache")]
    if production:
        headers.append((b"strict-transport-security", b"max-age=31536000; includeSubDomains"))
    return headers


class AppMiddleware:
    def __init__(self, app: Any, *, settings: Any, counters: RequestCounters, docs_enabled: bool) -> None:
        self.app = app
        self.settings = settings
        self.counters = counters
        self.docs_enabled = docs_enabled
        self.upload_limit = int(settings.max_upload_bytes) + 1024 * 1024

    async def __call__(self, scope: dict, receive: Any, send: Any) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return
        start = time.perf_counter()
        client_rid = None
        for name, value in scope.get("headers", []):
            if name == b"x-request-id":
                cand = value.decode("latin-1")
                client_rid = cand if _CLIENT_RID_RE.match(cand) else None
        rid = uuid.uuid4().hex            # L8: never taken from the client
        state = scope.setdefault("state", {})
        state["request_id"] = rid
        state["client_request_id"] = client_rid
        xff_error = False
        try:
            state["client_ip"] = client_ip(
                scope, bool(self.settings.trust_forwarded_for),
                hops=int(getattr(self.settings, "trusted_proxy_hops", 1) or 1),
                trusted_proxy_cidrs=list(getattr(self.settings, "trusted_proxy_cidrs", []) or []))
        except ForwardedForError:
            xff_error = True
            client = scope.get("client")
            state["client_ip"] = (_valid_ip(client[0]) or client[0]) if client else None
        path = scope.get("path", "")
        limit = self.upload_limit if (path == UPLOAD_PATH and scope.get("method") == "POST") else JSON_BODY_LIMIT

        declared = None
        for name, value in scope.get("headers", []):
            if name == b"content-length":
                try:
                    declared = int(value)
                except ValueError:
                    declared = -1
        status_holder = {"status": 500, "started": False}
        extra = _security_headers(path, self.docs_enabled, self.settings.env == "production")

        async def send_wrapper(message: dict) -> None:
            if message["type"] == "http.response.start":
                status_holder["status"] = message["status"]
                status_holder["started"] = True
                headers = [(k, v) for k, v in message.get("headers", [])
                           if k.lower() not in {h for h, _ in extra}]
                headers += extra
                headers.append((b"x-request-id", rid.encode()))
                if client_rid:
                    headers.append((b"x-client-request-id", client_rid.encode()))
                message = {**message, "headers": headers}
            await send(message)

        async def reject(status: int, code: str) -> None:
            body = json.dumps({"error": code, "reasons": [], "request_id": rid}).encode()
            await send_wrapper({"type": "http.response.start", "status": status,
                                "headers": [(b"content-type", b"application/json"),
                                            (b"content-length", str(len(body)).encode())]})
            await send_wrapper({"type": "http.response.body", "body": body})

        # F5: ambient audit context (request id + client IP; get_caller adds
        # the actor) for every audit event recorded while this request runs.
        audit_token = begin_request(rid, state["client_ip"], client_rid)
        try:
            if xff_error:
                log.warning("rejected request with malformed X-Forwarded-For",
                            extra={"request_id": rid})
                await reject(400, "bad-forwarded-for")
                return
            if declared is not None and (declared < 0 or declared > limit):
                await reject(413 if declared > limit else 400, "request-too-large" if declared > limit
                             else "bad-request")
                return
            seen = 0

            async def receive_wrapper() -> dict:
                nonlocal seen
                message = await receive()
                if message["type"] == "http.request":
                    seen += len(message.get("body", b""))
                    if seen > limit:
                        raise BodyTooLarge()
                return message

            try:
                await self.app(scope, receive_wrapper, send_wrapper)
            except BodyTooLarge:
                if not status_holder["started"]:
                    await reject(413, "request-too-large")
        finally:
            end_request(audit_token)
            self.counters.inc(status_holder["status"])
            route = scope.get("route")
            log.info("request", extra={
                "request_id": rid, "method": scope.get("method"),
                "path": getattr(route, "path", None) or path,
                "status": status_holder["status"],
                "duration_ms": round((time.perf_counter() - start) * 1000, 1)})
