import { Link } from "react-router-dom";
import { api } from "../api/client";
import type { Dashboard as DashboardData, ProviderHealth } from "../api/types";
import { Bars, Empty, ErrorNotice, PageHead, Panel, Pill, ProviderName, Updated, providerColor, statusTone } from "../components/ui";
import { EventTable } from "../components/EventTable";
import { bytes, num } from "../lib/format";
import { useApi } from "../lib/useApi";

export function Dashboard() {
  const q = useApi(() => api.get<DashboardData>("/api/dashboard"), [], 10_000);
  const d = q.data;
  return (
    <div className="page">
      <PageHead
        title="Dashboard"
        sub={d ? (d.scope === "all" ? "All users' committed data and the whole audit log." : "Your own files and your own audit events.") : undefined}
      >
        <Updated at={q.updatedAt} loading={q.loading} />
      </PageHead>
      <ErrorNotice error={q.error} onRetry={() => void q.reload()} />
      {!d && !q.error && <div className="muted">Loading…</div>}
      {d && (
        <>
          <div className="figures">
            <Figure label="Files committed" value={num(d.files.count)} />
            <Figure label="Encrypted chunks" value={num(d.files.chunks)} />
            <Figure label="Bytes stored (file size)" value={bytes(d.files.bytes)} />
            <Figure
              label="Providers available"
              value={`${d.providers_available} of ${d.providers_total}`}
              tone={d.providers_available < d.providers_total ? "warn" : undefined}
            />
          </div>

          <div className="grid-2">
            <Panel title="Ciphertext per provider" actions={<Link to="/distribution">Distribution</Link>}>
              {Object.keys(d.distribution).length === 0 ? (
                <Empty />
              ) : (
                <Bars
                  format={bytes}
                  rows={Object.entries(d.distribution).map(([p, v]) => ({
                    key: p,
                    label: <ProviderName name={p} />,
                    value: v.bytes,
                    tone: providerColor(p),
                    detail: `(${num(v.replicas)} replica${v.replicas === 1 ? "" : "s"})`,
                  }))}
                />
              )}
              <p className="muted small">Each chunk is stored on several providers; no single provider holds a whole file.</p>
            </Panel>

            <Panel title="Operations by outcome" actions={<span className="muted small">{num(d.operations.total)} audited</span>}>
              {d.operations.total === 0 ? (
                <Empty />
              ) : (
                <Bars
                  format={num}
                  rows={(["success", "denied", "failure", "error"] as const).map((o) => ({
                    key: o,
                    label: o === "success" ? "Succeeded" : o === "denied" ? "Denied by policy" : o === "failure" ? "Failed" : "Errored",
                    value: d.operations.by_outcome[o] ?? 0,
                    tone: o === "success" ? "var(--ok)" : o === "denied" ? "var(--warn)" : "var(--crit)",
                  }))}
                />
              )}
              {d.operations.by_event_prefix && Object.keys(d.operations.by_event_prefix).length > 0 && (
                <div className="chips">
                  {Object.entries(d.operations.by_event_prefix)
                    .sort((a, b) => b[1] - a[1])
                    .map(([k, v]) => (
                      <span key={k} className="chip">
                        {k} <b>{num(v)}</b>
                      </span>
                    ))}
                </div>
              )}
            </Panel>
          </div>

          <Panel title="Provider health">
            <ProviderStrip providers={d.providers} />
          </Panel>

          <Panel title="Recent security events" actions={<Link to="/security">Security centre</Link>}>
            {d.recent_security_events.length === 0 ? <Empty>No security events recorded</Empty> : <EventTable events={d.recent_security_events} compact />}
          </Panel>

          <p className="muted small">
            Files by status: {Object.entries(d.files.by_status).map(([k, v]) => `${k} ${v}`).join(", ")}. Generated by the server at{" "}
            {new Date(d.generated_at).toLocaleTimeString()}.
          </p>
        </>
      )}
    </div>
  );
}

function Figure({ label, value, tone }: { label: string; value: string; tone?: "warn" }) {
  return (
    <div className={`figure${tone ? ` figure-${tone}` : ""}`}>
      <div className="figure-value">{value}</div>
      <div className="figure-label">{label}</div>
    </div>
  );
}

export function ProviderStrip({ providers }: { providers: ProviderHealth[] }) {
  if (providers.length === 0) return <Empty />;
  return (
    <div className="pstrip">
      {providers.map((p) => (
        <div key={p.provider} className={`pcell${p.healthy === false ? " down" : ""}`}>
          <ProviderName name={p.provider} />
          <div className="row wrap">
            <Pill tone={p.healthy === null ? "neutral" : p.healthy ? "ok" : "crit"}>
              {p.healthy === null ? "not yet checked" : p.healthy ? "healthy" : "unhealthy"}
            </Pill>
            <Pill tone={statusTone(p.state)} title="Circuit breaker state">
              circuit {p.state}
            </Pill>
            {p.injected && <Pill tone="crit">SIMULATED FAULT {p.fault_mode}</Pill>}
          </div>
          <div className="muted small">
            {p.latency_ms !== null ? `${p.latency_ms.toFixed(1)} ms` : "no latency sample"}, {p.consecutive_failures} consecutive failures
          </div>
        </div>
      ))}
    </div>
  );
}
